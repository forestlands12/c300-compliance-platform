"""Read-only PowerShell snippets that collect Windows 11 settings.

Each snippet prints ONE small JSON object. The scanner runs them one by one over
WinRM (WinRMTarget) or, offline, all together from collect_windows.ps1
(`python -m compliance_checker export-windows-script`). collectors.windows_facts()
turns the combined output into normalised facts.

WHY small snippets: pywinrm sends a script as one encoded command line, and
Windows command lines max out at 8191 characters, so one big script would fail.
SECURITY: every snippet only reads. secedit writes its export to a temp file,
which is deleted straight away.
# TODO(Jayen, T-10): run every snippet on the real Windows 11 VMs and compare with the GUI.
"""
from __future__ import annotations

# WHAT: helper to read one registry value, returning $null when it is absent.
_REG = ("function R($p,$n){ try { (Get-ItemProperty -Path $p -Name $n -ErrorAction Stop).$n }"
        " catch { $null } }\n")

SNIPPETS: dict[str, str] = {
    # Password, lockout, guest account (Local Security Policy). Needs administrator.
    "secpol": r"""
$f = Join-Path $env:TEMP ('cc_' + [guid]::NewGuid().ToString() + '.inf')
secedit /export /cfg $f /areas SECURITYPOLICY /quiet | Out-Null
if (Test-Path $f) {
  $t = Get-Content -Raw -Path $f; Remove-Item -Force $f
  @{ inf = $t } | ConvertTo-Json -Compress
} else { @{ _error = 'secedit export failed (run as administrator)' } | ConvertTo-Json -Compress }
""",
    "firewall": r"""
$p = @{}
Get-NetFirewallProfile | ForEach-Object { $p[[string]$_.Name] = ([string]$_.Enabled -eq 'True') }
@{ profiles = $p } | ConvertTo-Json -Compress
""",
    "defender": r"""
try {
  $s = Get-MpComputerStatus -ErrorAction Stop
  @{ antivirus_enabled = [bool]$s.AntivirusEnabled; realtime_enabled = [bool]$s.RealTimeProtectionEnabled;
     signature_age_days = [int]$s.AntivirusSignatureAge } | ConvertTo-Json -Compress
} catch { @{ _error = $_.Exception.Message } | ConvertTo-Json -Compress }
""",
    "system": _REG + r"""
$ts = 'HKLM:\System\CurrentControlSet\Control\Terminal Server'
$pol = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies'
@{
  smb1 = $(try { [bool](Get-SmbServerConfiguration -ErrorAction Stop).EnableSMB1Protocol } catch { $null })
  rdp_deny = R $ts 'fDenyTSConnections'
  rdp_nla = R "$ts\WinStations\RDP-Tcp" 'UserAuthentication'
  uac_lua = R "$pol\System" 'EnableLUA'
  inactivity_secs = R "$pol\System" 'InactivityTimeoutSecs'
  autorun = R "$pol\Explorer" 'NoDriveTypeAutoRun'
  au_disabled = R 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate\AU' 'NoAutoUpdate'
} | ConvertTo-Json -Compress
""",
    # REF: subcategory GUID for "Logon" so the check works on any display language.
    "audit": r"""
$o = auditpol /get /subcategory:'{0CCE9215-69AE-11D9-BED3-505054503030}' /r | Where-Object { $_ } | ConvertFrom-Csv
if ($o) { @{ logon_inclusion = [string]@($o)[0].'Inclusion Setting'; logon_value = [string]@($o)[0].'Setting Value' } | ConvertTo-Json -Compress }
else { @{ _error = 'auditpol failed (run as administrator)' } | ConvertTo-Json -Compress }
""",
    "bitlocker": r"""
try {
  $v = Get-BitLockerVolume -MountPoint $env:SystemDrive -ErrorAction Stop
  @{ protection = [string]$v.ProtectionStatus } | ConvertTo-Json -Compress
} catch { @{ _error = $_.Exception.Message } | ConvertTo-Json -Compress }
""",
    "patches": r"""
$h = Get-HotFix | Where-Object { $_.InstalledOn } | Sort-Object InstalledOn -Descending | Select-Object -First 1
@{
  last_patch_days = $(if ($h) { [int]((Get-Date) - $h.InstalledOn).TotalDays } else { $null })
  last_kb = [string]$h.HotFixID
  os_caption = [string](Get-CimInstance Win32_OperatingSystem).Caption
  os_build = [string][Environment]::OSVersion.Version
  hostname = [string]$env:COMPUTERNAME
} | ConvertTo-Json -Compress
""",
}


# WHAT: Build one standalone script for offline mode (run on the VM, copy the JSON back).
def offline_script() -> str:
    parts = [
        "# C300 compliance collector for Windows 11 (read-only). Generated by",
        "#   python -m compliance_checker export-windows-script",
        "# Run in an Administrator PowerShell on the VM:",
        "#   powershell -ExecutionPolicy Bypass -File .\\collect_windows.ps1 -OutFile C:\\temp\\facts.json",
        "# then copy facts.json to the scanner PC and point a 'file' host in the inventory at it.",
        "param([string]$OutFile = \"$env:COMPUTERNAME-facts.json\")",
        "$out = [ordered]@{}",
    ]
    for name, body in SNIPPETS.items():
        parts.append(f"$out['{name}'] = (& {{\n{body.strip()}\n}}) | ConvertFrom-Json")
    parts.append("$out | ConvertTo-Json -Depth 5 | Set-Content -Encoding UTF8 -Path $OutFile")
    parts.append("Write-Host \"Saved $OutFile\"")
    return "\n".join(parts) + "\n"
